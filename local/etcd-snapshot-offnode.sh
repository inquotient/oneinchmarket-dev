#!/usr/bin/env bash
# k3s etcd 스냅숏을 **다른 노드로** 복사한다 (2026-11-08, Gotcha 225).
#
# 왜 필요한가
#   2026-11-08 에 데이터스토어를 내장 etcd 로 옮겼고(Gotcha 223) k3s 가 12시간마다 스냅숏을 뜬다.
#   그런데 그 자리(/var/lib/rancher/k3s/server/db/snapshots)는 **서버와 같은 디스크**라 103 을 잃으면
#   스냅숏도 함께 잃는다 — 백업이 가장 필요한 순간에 없다.
#
# 왜 S3(--etcd-s3)가 아닌가
#   이 클러스터의 S3 는 SeaweedFS 이고 **클러스터 안**에 있다. 복원이 필요한 때는 클러스터가 죽어 있을 때라
#   그 S3 도 함께 쓸 수 없다(순환 의존). 그래서 다른 노드의 디스크로 rsync 한다. 클러스터 밖 S3 가 생기면
#   그쪽(--etcd-s3)이 더 낫다.
#
# 무엇을 복사하나
#   ① 스냅숏 파일 전부(로컬 보존은 k3s 기본 5개) ② **서버 토큰** — 스냅숏 안의 부트스트랩 데이터가 그 토큰으로
#   암호화돼 있어 복원에 필요하다(`k3s server --cluster-reset --cluster-reset-restore-path=<파일> --token=<토큰>`).
#   대상은 root 전용(0700/0600)이다. 104 는 원래 조인용 K3S_TOKEN 을 들고 있던 노드다.
#
# 사용 (control-plane 에서 root 로)
#   local/etcd-snapshot-offnode.sh install    # 복사 스크립트 + systemd 서비스·타이머 설치, 한 번 실행
#   local/etcd-snapshot-offnode.sh run        # 지금 한 번 복사
#   local/etcd-snapshot-offnode.sh --check    # 최신 로컬 스냅숏이 원격에 같은 해시로 있는지 (0/1/2)
#
# ★ 생성하는 파일은 ASCII 만 쓴다(Gotcha 177) — 쓰기 전에 검사하고 아니면 쓰지 않는다.
# ★ 대상 노드는 kubectl 로 정하지 않는다 — 복원할 때는 API 가 없다. 고정값을 쓰고 바꿀 때는 DEST_HOST 로 준다.
set -euo pipefail

DEST_HOST="${DEST_HOST:-192.168.0.104}"
DEST_DIR="${DEST_DIR:-/var/backups/k3s-etcd}"
KEEP="${KEEP:-14}"                      # 원격 보존 개수(12시간마다 -> 7일)
SNAP_DIR=/var/lib/rancher/k3s/server/db/snapshots
TOKEN=/var/lib/rancher/k3s/server/token
BIN=/usr/local/sbin/oim-etcd-snapshot-copy
UNIT=oim-etcd-snapshot-copy
SSH="ssh -o BatchMode=yes -o ConnectTimeout=10 root@${DEST_HOST}"

ascii_only() { [ "$(LC_ALL=C grep -c '[^ -~	]' "$1" || true)" = 0 ]; }

write_copy_script() {
  local tmp; tmp=$(mktemp)
  cat > "$tmp" <<EOF
#!/usr/bin/env bash
# generated by local/etcd-snapshot-offnode.sh - do not edit here
set -euo pipefail
SSH="ssh -o BatchMode=yes -o ConnectTimeout=10 root@${DEST_HOST}"
\$SSH "install -d -m 0700 ${DEST_DIR} ${DEST_DIR}/snapshots"
rsync -a --chmod=F600 -e "ssh -o BatchMode=yes -o ConnectTimeout=10" ${SNAP_DIR}/ root@${DEST_HOST}:${DEST_DIR}/snapshots/
rsync -a --chmod=F600 -e "ssh -o BatchMode=yes -o ConnectTimeout=10" ${TOKEN} root@${DEST_HOST}:${DEST_DIR}/server-token
# keep the newest ${KEEP} snapshots on the destination
\$SSH "cd ${DEST_DIR}/snapshots && ls -1t | tail -n +$((KEEP + 1)) | xargs -r rm -f --"
newest=\$(ls -1t ${SNAP_DIR} | head -1)
[ -n "\$newest" ] || { echo "no local snapshot" >&2; exit 1; }
a=\$(sha256sum "${SNAP_DIR}/\$newest" | cut -d' ' -f1)
b=\$(\$SSH "sha256sum '${DEST_DIR}/snapshots/\$newest'" | cut -d' ' -f1)
[ "\$a" = "\$b" ] || { echo "checksum mismatch for \$newest" >&2; exit 1; }
echo "copied: newest=\$newest sha256=\${a:0:16}"
EOF
  ascii_only "$tmp" || { echo "[offnode] 생성한 복사 스크립트에 비-ASCII 가 있다 — 쓰지 않는다" >&2; rm -f "$tmp"; exit 1; }
  bash -n "$tmp"
  install -m 0700 "$tmp" "$BIN"; rm -f "$tmp"
}

write_units() {
  local svc tim
  svc=$(mktemp); tim=$(mktemp)
  cat > "$svc" <<EOF
[Unit]
Description=Copy k3s etcd snapshots to ${DEST_HOST} (oneinchmarket)
After=network-online.target k3s.service
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=${BIN}
EOF
  # k3s 기본 스냅숏 일정은 '0 */12 * * *'(노드 로컬 시각)이다 — 그 20분 뒤에 돈다. Persistent 로 놓친 회차를 메운다.
  cat > "$tim" <<EOF
[Unit]
Description=Copy k3s etcd snapshots off-node twice a day

[Timer]
OnCalendar=*-*-* 00,12:20:00
Persistent=true
RandomizedDelaySec=120

[Install]
WantedBy=timers.target
EOF
  for f in "$svc" "$tim"; do ascii_only "$f" || { echo "[offnode] 유닛에 비-ASCII 가 있다 — 쓰지 않는다" >&2; exit 1; }; done
  install -m 0644 "$svc" "/etc/systemd/system/${UNIT}.service"
  install -m 0644 "$tim" "/etc/systemd/system/${UNIT}.timer"
  rm -f "$svc" "$tim"
  systemctl daemon-reload
  systemctl enable --now "${UNIT}.timer" >/dev/null
}

check() {
  [ -d "$SNAP_DIR" ] || { echo "[측정 불가] 로컬 스냅숏 디렉터리가 없다 — 이 노드가 etcd 서버인가" >&2; return 2; }
  local newest a b
  newest=$(ls -1t "$SNAP_DIR" | head -1)
  [ -n "$newest" ] || { echo "[실패] 로컬 스냅숏이 0개다"; return 1; }
  a=$(sha256sum "$SNAP_DIR/$newest" | cut -d' ' -f1)
  # ★ 닿는지와 사본이 있는지를 따로 묻는다 — 한 줄로 물으면 사본이 없을 때(원격 sha256sum 실패)도
  #   "닿지 못했다" 가 되어 설치가 안 된 상태를 측정 불가로 읽는다(2026-11-08 실제로 그렇게 보고했다).
  $SSH true 2>/dev/null || { echo "[측정 불가] ${DEST_HOST} 에 닿지 못했다" >&2; return 2; }
  b=$($SSH "sha256sum '$DEST_DIR/snapshots/$newest' 2>/dev/null || true" | cut -d' ' -f1)
  local tok; tok=$($SSH "test -s '$DEST_DIR/server-token' && echo yes || echo no")
  local age=$(( ($(date +%s) - $(stat -c %Y "$SNAP_DIR/$newest")) / 3600 ))
  echo "최신 로컬 스냅숏: $newest (${age}시간 전)"
  echo "원격 사본: $([ "$a" = "$b" ] && echo '같은 해시' || echo '없음 또는 다름') · 토큰 사본: $tok"
  # is-enabled 는 없는 유닛에도 "not-found" 를 찍고 0 이 아닌 값을 낸다 — 출력만 쓴다
  local en; en=$(systemctl is-enabled "${UNIT}.timer" 2>/dev/null || true)
  echo "타이머: ${en:-없음} · 다음 실행: $(systemctl show "${UNIT}.timer" -p NextElapseUSecRealtime --value 2>/dev/null || true)"
  [ "$en" = enabled ] || { echo "[실패] 타이머가 없다 — install 을 돌릴 것"; return 1; }
  [ "$a" = "$b" ] && [ "$tok" = yes ] || { echo "[실패] 원격 사본이나 토큰 사본이 없다"; return 1; }
  [ "$age" -le 13 ] || { echo "[실패] 최신 스냅숏이 13시간보다 오래됐다 — k3s 의 스냅숏 일정을 볼 것"; return 1; }
  echo "판정: 통과"
}

case "${1:-}" in
  install) write_copy_script; write_units; "$BIN"; check ;;
  run)     "$BIN" ;;
  --check) check ;;
  *) echo "usage: $0 install|run|--check" >&2; exit 2 ;;
esac
